"""MEMORY.md: what sora knows, as a file you can open, read and diff.

The database is the source of truth; this file is a one-way copy, rewritten
after every change to facts or episodes. One way on purpose: if edits here
flowed back, a stray keystroke in an editor would silently become a "fact"
the assistant acts on. To change memory, tell sora ("forget that...") or
use the dashboard's Memory tab.

The file is written to a temporary name and then renamed over the old one,
so an editor or `cat` never sees half a file.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone
from pathlib import Path

EPISODES = 30           # most recent; older ones stay searchable, just not listed

HEADER = """# What sora remembers

> Generated by sora from its memory ({backend}); edits here are not read back.
> Change memory by telling sora, or in the dashboard's Memory tab.
> Updated {now} UTC · {facts} facts · {episodes} episodes
"""


def render(semantic, backend: str) -> str:
    facts = semantic.list_facts()
    episodes = semantic.list_episodes()
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M")
    lines = [HEADER.format(backend=backend, now=now, facts=len(facts), episodes=len(episodes)),
             "## Facts", ""]
    lines += [f"- {f['content']}  _({f['created_at'][:10]}, {f['source']})_" for f in facts] or ["_None yet._"]
    lines += ["", f"## Recent episodes", ""]
    lines += [f"- **{e['created_at'][:10]}** {e['summary']}" for e in episodes[:EPISODES]] or ["_None yet._"]
    if len(episodes) > EPISODES:
        lines.append(f"- _…and {len(episodes) - EPISODES} older_")
    return "\n".join(lines) + "\n"


def write(path: Path, semantic, backend: str) -> None:
    tmp = path.with_suffix(".md.tmp")
    tmp.write_text(render(semantic, backend), encoding="utf-8")
    os.replace(tmp, path)


def attach(store, path: Path) -> None:
    """Keep `path` in step with the store's facts and episodes from now on."""
    semantic = store.semantic
    semantic.on_change = lambda: write(path, semantic, semantic.name)
    write(path, semantic, semantic.name)
